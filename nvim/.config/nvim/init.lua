  vim.o.number = true
  vim.o.relativenumber = true

  vim.o.mouse = 'a'
  vim.o.showmode = false -- mode is already in statusline

  -- sync system and nvim clipboards
  -- see `:help 'clipboard'`
  vim.schedule(function() vim.o.clipboard = 'unnamedplus' end)

  -- Enable break indent
  vim.o.breakindent = true

  -- Enable undo/redo changes even after closing and reopening a file
  vim.o.undofile = true

